#!/usr/bin/env python3
"""Build the advertiser prototype from verified, read-only local API responses.

The generated preview has no runtime data network dependency. The snapshot keeps
source units/periods/releases and exact geography; it never creates missing rows.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
import json
from pathlib import Path
import subprocess
from urllib.parse import urlencode
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'ux' / 'advertising' / 'snapshot'


def build(base_url, esbuild):
    def read_api(path):
        with urlopen(base_url + path, timeout=30) as response:
            return json.load(response)

    catalog = read_api('/api/atlas/catalog')
    fields = sorted({m['fieldId'] for m in catalog['metrics'] if m.get('fieldId')})
    def read_series(field):
        payload = read_api('/api/atlas/observations?' + urlencode({'field': field}))
        if payload['fieldId'] != field:
            raise ValueError('Unexpected series: ' + field)
        return field, payload
    with ThreadPoolExecutor(max_workers=4) as pool:
        observations = dict(pool.map(read_series, fields))

    files = {
        '/node_modules/us-atlas/counties-10m.json': ROOT / 'node_modules/us-atlas/counties-10m.json',
        '/node_modules/world-atlas/countries-110m.json': ROOT / 'node_modules/world-atlas/countries-110m.json',
        '/ux/county-boundary-repair.json': ROOT / 'ux/county-boundary-repair.json',
        '/ux/cities.json': ROOT / 'ux/cities.json',
        '/ux/view-settings.json': ROOT / 'ux/view-settings.json',
    }
    files.update({'/ux/boundaries/' + p.name: p for p in (ROOT / 'ux/boundaries').glob('*.json') if p.stem.isdigit()})
    assets = {path: json.loads(file.read_text()) for path, file in files.items()}
    captured = datetime.now(timezone.utc).isoformat()
    snapshot = {'capturedAt': captured, 'catalog': catalog, 'observations': observations, 'assets': assets}
    DEST.mkdir(exist_ok=True)
    (DEST / 'data.json').write_text(json.dumps(snapshot, separators=(',', ':')))
    (DEST / 'catalog.js').write_text('// Generated by scripts/build_ad_preview.py. Public read-only catalog.\nexport const capturedAt = ' + json.dumps(captured) + ';\nexport const catalogSnapshot = ' + json.dumps(catalog, separators=(',', ':')) + ';\n')
    subprocess.run([esbuild, 'ux/advertising/preview-entry.js', '--bundle', '--format=esm', '--minify', '--inject:ux/advertising/snapshot-loader.js', '--outfile=ux/advertising/preview.bundle.js', '--legal-comments=linked', '--metafile=ux/advertising/snapshot/bundle-meta.json'], cwd=ROOT, check=True)
    metadata = json.loads((DEST / 'bundle-meta.json').read_text())
    packages = sorted({path.split('/')[1] for path in metadata['inputs'] if path.startswith('node_modules/')})
    licenses = []
    for name in packages:
        folder = ROOT / 'node_modules' / name
        package = json.loads((folder / 'package.json').read_text())
        license_files = sorted(folder.glob('LICENSE*'))
        if not license_files:
            raise ValueError('Missing bundled license for ' + name)
        licenses.append(name + ' ' + package['version'] + ' (' + package.get('license', 'see text') + ')\n' + license_files[0].read_text())
    (DEST.parent / 'THIRD_PARTY_LICENSES.txt').write_text('\n\n'.join(licenses))
    print(f'Captured {len(fields)} series and {len(files)} geography/settings files at {captured}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--base-url', default='http://127.0.0.1:4180')
    parser.add_argument('--esbuild', required=True, help='Path to an installed esbuild CLI')
    args = parser.parse_args()
    build(args.base_url.rstrip('/'), args.esbuild)
